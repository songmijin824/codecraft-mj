// 전체 통합 Map

type IconComponentType = React.FC<React.SVGProps<SVGSVGElement>>;

export const iconMap: Record<string, Record<string, IconComponentType>> = {
  normal: normalIconMap as unknown as Record<string, IconComponentType>,
  block: blockIconMap as unknown as Record<string, IconComponentType>,
  thick: thickIconMap as unknown as Record<string, IconComponentType>,
};

interface IconProps {
  name: string;
  type?: 'normal' | 'block';
  size?: number;
  className?: string;
  color?: string;
}

// 아이콘 컴포넌트 설명
// svg 파일자체에 style이 지정되어 있으면 fill이 적용되지 않음, 
// 또 color 속성은 currentColor로 지정해야 fill이 적용됨, 
// width와 height도 정해져있으면 size 상속하지않음

export default function Icon({ name = '01', type = 'normal', size = 24, className, color }: IconProps) {
  const targetMap = iconMap[type];
  const iconKey = `${type}_${name}`;
  
  // 여기서 SelectedIcon은 이제 'IconComponentType' 임을 알게 됩니다.
  const SelectedIcon = targetMap[iconKey];

  if (!SelectedIcon) return null;

  return <SelectedIcon 
  width={size} height={size} 
  className={className} 
  fill="currentColor"       
  style={{ color: color }} 
  />;
}

